export function uiText(english: string): string {
	if (appI18n.resolvedLanguage !== "zh-CN") return english;
	const exact = zhCNLegacyUi[english];
	if (exact) return exact;

	const orchestratorMismatch = /^Configured orchestrator agent is (.+); running agent is (.+)\.$/.exec(english);
	if (orchestratorMismatch) {
		return `配置的编排器智能体是 ${orchestratorMismatch[1]}，当前运行的是 ${orchestratorMismatch[2]}。`;
	}

	const spawnFailure = /^Failed to spawn orchestrator \((\d+)\)$/.exec(english);
	if (spawnFailure) return `启动编排器失败（状态码 ${spawnFailure[1]}）`;

	const statusFailure =
		/^(Failed to (?:pin session|unpin session|terminate session|rename session|resume agent|update merge policy)) \((\d+)\)$/.exec(
			english,
		);
	if (statusFailure) {
		return `${zhCNLegacyUi[statusFailure[1]] ?? statusFailure[1]}（状态码 ${statusFailure[2]}）`;
	}

	return english;
}

export function hasZhCNLegacyUi(english: string): boolean {
	return Object.hasOwn(zhCNLegacyUi, english);
}
